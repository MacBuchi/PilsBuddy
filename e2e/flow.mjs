await step('beer report: brewery sheet → „Bier fehlt?“ → validated, sent (request stubbed – no real issue)', async () => {
  let sent = null
  await page.route('**/rest/v1/beer_submissions', (r) => {
    sent = r.request().postDataJSON()
    return r.fulfill({ status: 201, body: '' })
  })
  await m.getByRole('button', { name: /Biere aus deiner Nähe/ }).click()
  await m.locator('button[class*="reco"]').first().click()
  const dialog = m.locator('[role=dialog]')
  const brewery = (await dialog.locator('h2, [class*="title"]').first().innerText()).trim()
  await dialog.getByRole('button', { name: /Bier fehlt\? Eintragen/ }).click()
  await see('Ein Link reicht')
  await m.getByRole('button', { name: 'Melden' }).click()
  await see('eins davon brauchen wir')
  await m.getByLabel('Name des Biers').fill('E2E Testbier')
  await m.getByLabel('Bierstil').selectOption('Kellerbier')
  await m.getByLabel('Alkohol (% vol)').fill('5,2')
  await page.screenshot({ path: `${out}-beer-report.png` })
  await m.getByRole('button', { name: 'Melden' }).click()
  await see('Deine Meldung ist unterwegs')
  if (!sent?.brewery_id || sent.brewery_name !== brewery || sent.beer_name !== 'E2E Testbier' || sent.style !== 'Kellerbier' || sent.abv !== 5.2)
    throw new Error('unexpected payload ' + JSON.stringify(sent))
  if (Object.keys(sent).sort().join() !== 'abv,app_version,beer_name,brewery_id,brewery_name,platform,style') throw new Error('extra fields ' + Object.keys(sent))
  await m.getByRole('button', { name: 'Schließen' }).click()
  await page.unroute('**/rest/v1/beer_submissions')
  await m.getByLabel('Zurück').click()
  await see('entschlüsselt')
})
