// End-to-end: fresh user → onboarding → swipes → DNA → avatar → match → detail → back → reload resumes.
import { chromium, devices } from 'playwright'

const base = process.argv[2] ?? 'http://localhost:5179/'
const out = process.argv[3] ?? '/tmp/flow'
const browser = await chromium.launch()
const ctx = await browser.newContext({
  ...devices['iPhone 14'],
  deviceScaleFactor: 2,
  locale: 'de-DE', // the steps read German texts; English has its own step (I1)
  permissions: ['clipboard-read', 'clipboard-write', 'geolocation'],
  geolocation: { latitude: 49.2386, longitude: 9.1016 }, // Bad Rappenau – real regional data (R4)
})
const page = await ctx.newPage()
const errors = []
page.on('pageerror', (e) => errors.push(String(e)))
page.on('console', (m) => m.type() === 'error' && errors.push(m.text()))
const step = async (name, fn) => {
  try {
    await fn()
    console.log('ok  ', name)
  } catch (e) {
    console.log('FAIL', name, '-', String(e).split('\n')[0])
    await page.screenshot({ path: `${out}-fail.png` })
    await browser.close()
    process.exit(1)
  }
}
